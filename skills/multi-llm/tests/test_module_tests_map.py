def test_a_declared_sweep_covers_every_matching_module(tmp_path):
    tests_dir = _scratch(tmp_path)
    (tmp_path / "utils" / "providers").mkdir()
    for name in ("one", "two"):
        (tmp_path / "utils" / "providers" / f"{name}.py").write_text("", encoding="utf-8")
    (tests_dir / "test_loop.py").write_text("def test_x():\n    pass\n", encoding="utf-8")
    sweeps = (tests_for.Sweep("test_loop.py", ("utils.providers.*",), "loops the roster"),
              tests_for.Sweep("test_absent.py", ("utils.*",), "not in this tree"))
    mapping = tests_for.build_map(tests_dir, tests_for.source_modules(tmp_path), sweeps=sweeps)
    assert [i.via for i in mapping["utils.providers.one"]] == ["sweep"]
    assert [i.test for i in mapping["utils.providers.two"]] == ["test_loop.py"]
    assert [i.test for i in mapping["utils.alpha"]] == ["test_alpha.py"]


def test_the_declared_sweeps_name_real_files_modules_and_reasons():
    modules = tests_for.source_modules()
    for sweep in tests_for.SWEEPS:
        assert (tests_for.TESTS_DIR / sweep.test).is_file(), sweep.test
        assert sweep.reason.strip(), sweep.test
        for pattern in sweep.patterns:
            assert any(fnmatch.fnmatchcase(m, pattern) for m in modules), (sweep.test, pattern)


