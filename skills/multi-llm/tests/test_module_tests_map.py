"""The committed module-to-tests map stays in step with the test files.

``tests/MODULE_TESTS.md`` is generated by ``tests/tools/tests_for.py --write``
(``make tests-map``). A changed import, or a changed declared route, makes it
stale, and this is what tells the author to regenerate it; a test that maps to no
module does not. Pure and zero-spend.
"""

from __future__ import annotations

import fnmatch

import pytest

from .tools import tests_for


def test_the_committed_map_is_fresh():
    assert tests_for.check() is None, tests_for.check()


def test_the_stale_message_names_the_fix(tmp_path):
    problem = tests_for.check(tmp_path / "missing.md")
    assert problem is not None
    assert "make tests-map" in problem and "MODULE_TESTS.md" in problem


def _scratch(tmp_path):
    """A one-module tree: ``utils/alpha.py`` and ``tests/test_alpha.py`` importing it."""
    tests_dir = tmp_path / "tests"
    (tmp_path / "utils").mkdir()
    (tmp_path / "utils" / "alpha.py").write_text("X = 1\n", encoding="utf-8")
    tests_dir.mkdir()
    (tests_dir / "test_alpha.py").write_text("from utils import alpha\n", encoding="utf-8")
    return tests_dir


def test_a_test_that_maps_to_no_module_leaves_the_map_unchanged(tmp_path):
    tests_dir = _scratch(tmp_path)
    before = tests_for.generate(tests_dir)
    (tests_dir / "test_other.py").write_text("def test_x():\n    assert True\n", encoding="utf-8")
    assert tests_for.generate(tests_dir) == before
    assert "Scanned" not in before


def test_a_new_import_changes_the_map(tmp_path):
    tests_dir = _scratch(tmp_path)
    before = tests_for.generate(tests_dir)
    (tests_dir / "test_more.py").write_text("import utils.alpha\n", encoding="utf-8")
    assert tests_for.generate(tests_dir) != before


def test_check_fails_only_when_the_mapping_changed(tmp_path):
    tests_dir = _scratch(tmp_path)
    committed = tmp_path / "MODULE_TESTS.md"
    committed.write_bytes(tests_for.generate(tests_dir).encode("utf-8"))
    (tests_dir / "test_other.py").write_text("def test_x():\n    pass\n", encoding="utf-8")
    assert tests_for.check(committed, tests_dir) is None
    (tests_dir / "test_more.py").write_text("import utils.alpha\n", encoding="utf-8")
    assert "stale" in tests_for.check(committed, tests_dir)


def test_imports_are_attributed_and_ranked(tmp_path):
    tests_dir = tmp_path / "tests"
    (tmp_path / "utils" / "providers").mkdir(parents=True)
    (tmp_path / "utils" / "alpha.py").write_text("X = 1\n", encoding="utf-8")
    (tmp_path / "utils" / "providers" / "__init__.py").write_text("", encoding="utf-8")
    (tmp_path / "utils" / "providers" / "beta.py").write_text("", encoding="utf-8")
    tests_dir.mkdir()
    (tests_dir / "test_zzz.py").write_text("import utils.alpha\n", encoding="utf-8")
    (tests_dir / "test_aaa.py").write_text("from utils.alpha import X\n", encoding="utf-8")
    (tests_dir / "test_alpha.py").write_text("import utils.alpha\n", encoding="utf-8")
    (tests_dir / "test_p.py").write_text(
        "from utils.providers import beta\nfrom .helpers import x\n", encoding="utf-8"
    )
    modules = tests_for.source_modules(tmp_path)
    mapping = tests_for.build_map(tests_dir, modules)
    alpha = tests_for.ranked("utils.alpha", mapping["utils.alpha"], tests_dir)
    # name match, then a from-import of names, then the rest.
    assert [item.test for item in alpha] == ["test_alpha.py", "test_aaa.py", "test_zzz.py"]
    assert [item.test for item in mapping["utils.providers.beta"]] == ["test_p.py"]
    assert [item.test for item in mapping["utils.providers"]] == ["test_p.py"]


def test_a_support_modules_imports_count_for_the_tests_that_import_it(tmp_path):
    """A helper moved out of a test file into ``tests/support`` keeps that file's
    edges: what the support module imports, directly or through another support
    module, counts for each test file that imports it."""
    tests_dir = _scratch(tmp_path)
    (tmp_path / "utils" / "beta.py").write_text("", encoding="utf-8")
    (tmp_path / "utils" / "gamma.py").write_text("", encoding="utf-8")
    (tests_dir / "support").mkdir()
    (tests_dir / "support" / "world.py").write_text(
        "from utils import beta\nfrom tests.support.base import X\n", encoding="utf-8")
    (tests_dir / "support" / "base.py").write_text("import utils.gamma\nX = 1\n", encoding="utf-8")
    (tests_dir / "test_user.py").write_text("from tests.support.world import thing\n", encoding="utf-8")
    (tests_dir / "test_other.py").write_text("from tests.support import base\n", encoding="utf-8")
    mapping = tests_for.build_map(tests_dir, tests_for.source_modules(tmp_path), sweeps=())
    assert [item.test for item in mapping["utils.beta"]] == ["test_user.py"]
    assert [item.test for item in mapping["utils.gamma"]] == ["test_other.py", "test_user.py"]
    assert {item.via for item in mapping["utils.gamma"]} == {"support"}
    # A direct import outranks the same edge through a support module.
    (tests_dir / "test_user.py").write_text(
        "from tests.support.world import thing\nimport utils.beta\n", encoding="utf-8")
    mapping = tests_for.build_map(tests_dir, tests_for.source_modules(tmp_path), sweeps=())
    assert [item.via for item in mapping["utils.beta"]] == ["import"]


def test_a_registered_plugins_fixture_counts_for_the_tests_that_request_it(tmp_path):
    """A fixture served through ``conftest.py``'s ``pytest_plugins`` has no import
    in the test file; requesting it by name still brings the plugin's edges, unless
    the file defines or imports a fixture of that name itself (Codex, U41)."""
    tests_dir = _scratch(tmp_path)
    (tmp_path / "utils" / "beta.py").write_text("", encoding="utf-8")
    (tests_dir / "support").mkdir()
    (tests_dir / "support" / "world.py").write_text(
        "import pytest\nfrom utils import beta\n\n"
        "@pytest.fixture(name='repo')\ndef _repo():\n    return beta\n", encoding="utf-8")
    (tests_dir / "conftest.py").write_text(
        "pytest_plugins = ['tests.support.world']\n", encoding="utf-8")
    (tests_dir / "test_uses.py").write_text("def test_x(repo):\n    pass\n", encoding="utf-8")
    (tests_dir / "test_local.py").write_text(
        "import pytest\n\n@pytest.fixture\ndef repo():\n    return 1\n\n"
        "def test_y(repo):\n    pass\n", encoding="utf-8")
    (tests_dir / "test_imported.py").write_text(
        "from tests.support.other import repo\n\ndef test_z(repo):\n    pass\n",
        encoding="utf-8")
    mapping = tests_for.build_map(tests_dir, tests_for.source_modules(tmp_path), sweeps=())
    assert [item.test for item in mapping["utils.beta"]] == ["test_uses.py"]


