_DYNAMIC_FORMS = [
    'import importlib\nimportlib.import_module("utils.alpha")\n',
    'import importlib as il\nil.import_module("utils.alpha")\n',
    'import importlib.util\nimportlib.import_module(name="utils.alpha")\n',
    'from importlib import import_module\nimport_module("utils.alpha")\n',
    'from importlib import import_module as load\nload("utils.alpha")\n',
    '__import__("utils.alpha")\n',
    '__import__("utils", fromlist=["alpha"])\n',
    'def f():\n    import importlib\n    return importlib.import_module("utils.alpha")\n',
]
_NOT_LITERAL = [
    'import importlib\nimportlib.import_module("utils." + name)\n',
    'import importlib\nimportlib.import_module(name)\n',
    'import importlib\nimportlib.import_module(".alpha", package="utils")\n',
    'import importlib\nrunpy = None\nimportlib.reload(x)\n',
    'class Other:\n    def import_module(self, name): ...\nOther().import_module("utils.alpha")\n',
    'import runpy\nrunpy.run_module("utils.alpha")\n',
    '# importlib.import_module("utils.alpha")\nNOTE = \'__import__("utils.alpha")\'\n',
]


@pytest.mark.parametrize("source", _DYNAMIC_FORMS)
def test_a_literal_dynamic_import_is_an_edge(tmp_path, source):
    tests_dir = _scratch(tmp_path)
    (tests_dir / "test_alpha.py").write_text("def test_x():\n    pass\n", encoding="utf-8")
    (tests_dir / "test_dyn.py").write_text(source, encoding="utf-8")
    mapping = tests_for.build_map(tests_dir, tests_for.source_modules(tmp_path), sweeps=())
    assert [(i.test, i.via) for i in mapping["utils.alpha"]] == [("test_dyn.py", "dynamic")]


@pytest.mark.parametrize("source", _NOT_LITERAL)
def test_a_computed_relative_or_unrelated_load_is_not_an_edge(tmp_path, source):
    tests_dir = _scratch(tmp_path)
    (tests_dir / "test_alpha.py").write_text("def test_x():\n    pass\n", encoding="utf-8")
    (tests_dir / "test_dyn.py").write_text(source, encoding="utf-8")
    mapping = tests_for.build_map(tests_dir, tests_for.source_modules(tmp_path), sweeps=())
    assert mapping["utils.alpha"] == []


