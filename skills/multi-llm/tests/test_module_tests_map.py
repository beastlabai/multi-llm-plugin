def _harness_world(tmp_path):
    """A skill tree with one orchestrator mode, one runner key and an e2e suite."""
    tests_dir = _scratch(tmp_path)
    (tests_dir / "harness").mkdir()
    (tests_dir / "harness" / "skill_runner.py").write_text(
        'class SkillRunner:\n    ORCHESTRATORS = {"alpha_run": "alpha_orchestrator.py"}\n',
        encoding="utf-8",
    )
    (tmp_path / "modes.py").write_text(
        'MODES = (Mode(name="beta-mode", target_module="beta_orchestrator"),\n'
        '         Mode(name="status", target_module="utils.run_status"))\n',
        encoding="utf-8",
    )
    for name in ("alpha_orchestrator", "beta_orchestrator", "gamma_orchestrator"):
        (tmp_path / f"{name}.py").write_text("", encoding="utf-8")
    (tmp_path / "utils" / "run_status.py").write_text("", encoding="utf-8")
    return tests_dir


def test_a_harness_suite_maps_to_the_entry_points_it_drives(tmp_path):
    tests_dir = _harness_world(tmp_path)
    (tests_dir / "test_e2e_one.py").write_text(
        'def test_a(r):\n    r.run_orchestrator("alpha_run", "p")\n'
        '    r.run("beta-mode", "--status", "gamma_orchestrator.py")\n',
        encoding="utf-8",
    )
    suites = {"test_e2e_one.py": tests_for.HarnessSuite(("utils.alpha",), "declared")}
    mapping = tests_for.build_map(tests_dir, tests_for.source_modules(tmp_path), sweeps=(), suites=suites)
    for module in ("alpha_orchestrator", "beta_orchestrator", "gamma_orchestrator"):
        assert [(i.test, i.via) for i in mapping[module]] == [("test_e2e_one.py", "harness")]
    # A declared module is added; "status" is not an orchestrator mode, so no edge.
    assert {i.test for i in mapping["utils.alpha"]} == {"test_alpha.py", "test_e2e_one.py"}
    assert mapping["utils.run_status"] == []


def test_every_e2e_suite_has_a_harness_row_and_every_row_a_suite():
    suites = {path.name for path in tests_for.TESTS_DIR.glob(tests_for.HARNESS_GLOB)}
    assert suites, "no test_e2e_*.py found; HARNESS_GLOB is wrong"
    assert suites == set(tests_for.HARNESS_SUITES), (
        "add or remove a HARNESS_SUITES row in tests/tools/tests_for.py: "
        f"missing {sorted(suites - set(tests_for.HARNESS_SUITES))}, "
        f"stale {sorted(set(tests_for.HARNESS_SUITES) - suites)}"
    )
    modules = tests_for.source_modules()
    for name, suite in tests_for.HARNESS_SUITES.items():
        assert suite.reason.strip(), name
        assert all(module in modules for module in suite.modules), name


