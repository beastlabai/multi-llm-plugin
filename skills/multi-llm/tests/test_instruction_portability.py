def _capturing_target(store):
    """A ``_load_target`` stand-in that records the residual argv verbatim."""

    def loader(module_path, attr):
        def target(argv):
            store["argv"] = list(argv)
            store["module"] = module_path
            return 0

        return target

    return loader


