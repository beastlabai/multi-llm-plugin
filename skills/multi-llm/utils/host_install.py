# ---------------------------------------------------------------------------
# Generation, header block and the slots a template carries
# ---------------------------------------------------------------------------

#: The shim **shape** generation, bumped whenever a template's structure changes
#: (a new step, a new slot, a changed command form) — independent of any content
#: hash. One integer for every host, because one renderer produces every shim: a
#: mismatch means "generated by an older multi-llm", which ``--check`` row 4 can
#: report as exactly that instead of as an unexplained shape failure (D7b).
SHIM_VERSION = 1

#: The key that identifies a file as ours. ``uninstall-host`` removes files by
#: this block and **never** by filename, so a user's own `multi-llm.md` is safe.
HEADER_KEY = "multi_llm_shim"

#: The header line, per shim format. Markdown gets an HTML comment; a TOML-shaped
#: shim (no host ships one today) gets a `#` comment. Driven off the entry's
#: ``shim.format`` rather than off the host id.
_HEADER_SYNTAX: Dict[str, Tuple[str, str]] = {
    "markdown": ("<!-- ", " -->"),
    "markdown+frontmatter": ("<!-- ", " -->"),
    "toml": ("# ", ""),
}

#: One line, so removing it restores the body byte-for-byte (see :func:`body_of`).
_HEADER_RE = re.compile(
    r"^(?:<!--|#)\s*" + HEADER_KEY + r":\s*(\{[^{}]*\})", re.MULTILINE
)

#: Slot -> how it is filled. The three verb slots come from the capability data
#: (``host_capabilities.VERB_SLOTS``); the rest are install-time facts.
SLOT_UV_MISSING_TEXT = "{{uv_missing_text}}"
SLOT_UV_MISSING_FILE = "{{uv_missing_file}}"

#: Every ``{{…}}`` slot spelling the renderer knows, for the "no unfilled slot"
#: assertion. Snippet slots are derived from the files in ``hosts/snippets/``.
_SLOT_RE = re.compile(r"\{\{[a-z_]+\}\}")

#: Placeholder spellings that must never survive into an installed shim.
FORBIDDEN_IN_INSTALLED: Tuple[str, ...] = (
    "{SKILL_DIR}", "${SKILL_DIR}", "$SKILL_DIR", "$ARGUMENTS",
    "${CLAUDE_SKILL_DIR}",
)

#: The one placeholder that is legal in the one shim nobody renders: the reference
#: host expands ``${CLAUDE_SKILL_DIR}`` inside its own ``SKILL.md`` at load time
#: (D1b), so for an ``installable: false`` entry it is a binding, not a leftover.
_HOST_EXPANDED_PLACEHOLDER = "${CLAUDE_SKILL_DIR}"

#: Where the single-sourced uv install message lives, relative to the skill root.
UV_MISSING_RELATIVE = os.path.join("hosts", "uv-missing.txt")

#: Where the shared shim partials live, relative to the skill root.
SNIPPET_DIR = os.path.join("hosts", "snippets")

#: How many times a snippet may expand another snippet before we call it a loop.
_MAX_SNIPPET_DEPTH = 4


# ---------------------------------------------------------------------------
# Scopes and path tokens (D7c)
# ---------------------------------------------------------------------------

SCOPE_PROJECT = "project"
SCOPE_GLOBAL = "global"
SCOPE_LEGACY = "legacy"

#: Writable scopes, in the order ``--check`` reports them: the host's own
#: discovery precedence, recorded rather than assumed (project beats global on
#: every host surveyed).
WRITABLE_SCOPES: Tuple[str, ...] = (SCOPE_PROJECT, SCOPE_GLOBAL)

#: Default scope for a write. ``--global`` is the machine-wide install a user
#: expects from a one-off command; ``--project`` is the opt-in.
DEFAULT_SCOPE = SCOPE_GLOBAL

#: The per-user root tokens, in the order they are honoured. ``$HOME`` is what the
#: data spells; ``%USERPROFILE%`` is the same directory under native Windows and
#: is accepted as a token so a future entry may spell it either way.
_HOME_TOKENS: Tuple[str, ...] = ("$HOME", "${HOME}", "%USERPROFILE%", "~")

_XDG_TOKENS: Tuple[str, ...] = ("$XDG_CONFIG_HOME", "${XDG_CONFIG_HOME}")


def user_home(env: Optional[Dict[str, str]] = None) -> Path:
    """The per-user root a ``$HOME``/``~``/``%USERPROFILE%`` token expands to.

    ``HOME`` first (POSIX, and what Git Bash sets on Windows), then
    ``USERPROFILE`` (native Windows Python), then the interpreter's own answer.
    One function, so no caller re-derives the platform rule and a test can hand it
    a temp home on either platform.
    """
    env = os.environ if env is None else env
    for name in ("HOME", "USERPROFILE"):
        value = env.get(name)
        if value:
            return Path(value)
    return Path.home()


def expand_path_tokens(
    raw: str,
    *,
    env: Optional[Dict[str, str]] = None,
    project_root: Optional[Path] = None,
) -> Path:
    """Expand one ``install_paths`` entry into a native absolute directory.

    OS variance is a token expansion, not extra rows in the data: ``$HOME``/``~``
    is ``%USERPROFILE%`` on Windows, and the XDG-style roots honour
    ``$XDG_CONFIG_HOME`` when it is set (falling back to ``<home>/.config``, which
    is what the second global entry of an XDG host spells literally — the two
    collapse to one path and are de-duplicated by :func:`locations`).

    A relative entry is a project-scope path and resolves against *project_root*.
    """
    env = os.environ if env is None else env
    text = raw.strip()
    home = user_home(env)
    for token in _XDG_TOKENS:
        if text.startswith(token):
            configured = (env.get("XDG_CONFIG_HOME") or "").strip()
            root = Path(configured) if configured else home / ".config"
            return _join(root, text[len(token):])
    for token in _HOME_TOKENS:
        if text == token or text.startswith(token + "/"):
            return _join(home, text[len(token):])
    candidate = Path(text)
    if candidate.is_absolute():
        return candidate
    root = Path(project_root) if project_root is not None else Path.cwd()
    return _join(root, text)


def _join(root: Path, remainder: str) -> Path:
    remainder = remainder.lstrip("/")
    return Path(os.path.abspath(str(root / remainder) if remainder else str(root)))


# ---------------------------------------------------------------------------
# Where a host's shim can live
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class Location:
    """One place a host's shim may sit, with its precedence already decided."""

    host_id: str
    scope: str            # project | global | legacy
    writable: bool        # False for a compatibility location (read-only, D7)
    raw: str              # the unexpanded token form, for messages
    directory: Path
    path: Path

    @property
    def label(self) -> str:
        kind = "preferred" if self.writable else "compat"
        return f"{self.scope}/{kind}"


def shim_filename(host_id: str, base: Optional[str] = None) -> str:
    """The file name a host's shim takes.

    ``shim.installed`` is recorded relative to the host's own config root
    (``commands/multi-llm.md``, ``SKILL.md``) while ``install_paths`` names the
    directory to write into, so the file name is its basename. One rule, both
    hosts, no branch.
    """
    installed = caps.entry(host_id, base)["shim"]["installed"]
    return os.path.basename(installed.replace("\\", "/"))


def locations(
    host_id: str,
    *,
    base: Optional[str] = None,
    env: Optional[Dict[str, str]] = None,
    project_root: Optional[Path] = None,
) -> List[Location]:
    """Every location for *host_id*, in the host's discovery-precedence order.

    Precedence is the host's, not ours, and it is recorded rather than assumed: on
    every host surveyed project scope wins over global and a preferred root wins
    over a legacy one. A legacy entry belongs to the scope its own token implies —
    rooted at the user's home (or XDG) means global, relative means project — so
    the classification stays data-driven too.
    """
    entry = caps.entry(host_id, base)
    paths = entry["install_paths"]
    name = shim_filename(host_id, base)
    buckets: Dict[str, List[Tuple[str, bool]]] = {
        SCOPE_PROJECT: [(raw, True) for raw in paths[SCOPE_PROJECT]],
        SCOPE_GLOBAL: [(raw, True) for raw in paths[SCOPE_GLOBAL]],
    }
    for raw in paths[SCOPE_LEGACY]:
        scope = SCOPE_GLOBAL if _is_user_rooted(raw) else SCOPE_PROJECT
        buckets[scope].append((raw, False))

    found: List[Location] = []
    seen: set = set()
    for scope in WRITABLE_SCOPES:
        # Preferred roots first, then this scope's compatibility locations.
        for writable in (True, False):
            for raw, is_writable in buckets[scope]:
                if is_writable is not writable:
                    continue
                directory = expand_path_tokens(
                    raw, env=env, project_root=project_root
                )
                path = directory / name
                if str(path) in seen:
                    continue
                seen.add(str(path))
                found.append(
                    Location(
                        host_id=host_id,
                        scope=scope,
                        writable=writable,
                        raw=raw,
                        directory=directory,
                        path=path,
                    )
                )
    return found


def _is_user_rooted(raw: str) -> bool:
    text = raw.strip()
    return any(
        text == token or text.startswith(token + "/")
        for token in _HOME_TOKENS + _XDG_TOKENS
    ) or Path(text).is_absolute()


def target_location(
    host_id: str,
    scope: str = DEFAULT_SCOPE,
    *,
    base: Optional[str] = None,
    env: Optional[Dict[str, str]] = None,
    project_root: Optional[Path] = None,
) -> Location:
    """The one path a write goes to: the **first** preferred path of *scope*.

    Compatibility locations are supported deliberately and read-only: an existing
    install keeps working and ``--check`` finds it, but nothing new is ever created
    there. Migrating is: re-run ``install-host``, then delete the file it names.
    """
    for location in locations(
        host_id, base=base, env=env, project_root=project_root
    ):
        if location.scope == scope and location.writable:
            return location
    raise Refused(
        f"ERROR: host '{host_id}' declares no {scope}-scope install path.\n"
        f"       install_paths.{scope} is empty in hosts/capabilities.yaml, so "
        "there is nowhere to write. Pass the other scope, or add the path to the "
        "data (a host doc change is a data edit, never a code edit)."
    )


def existing_copies(
    host_id: str,
    *,
    base: Optional[str] = None,
    env: Optional[Dict[str, str]] = None,
    project_root: Optional[Path] = None,
) -> List[Location]:
    """Locations that hold a file today, in precedence order."""
    return [
        location
        for location in locations(
            host_id, base=base, env=env, project_root=project_root
        )
        if location.path.is_file()
    ]


class Refused(Exception):
    """An installer-owned refusal: exit 3, message already written for a human."""


# ---------------------------------------------------------------------------
# Rendering
# ---------------------------------------------------------------------------

def template_path(host_id: str, base: Optional[str] = None) -> Path:
    entry = caps.entry(host_id, base)
    template = entry["shim"]["template"]
    root = Path(str(base) if base else str(skill_dir()))
    if not template:
        raise Refused(
            f"ERROR: host '{host_id}' has no shim template.\n"
            f"       Its entry sets shim.template: null, which is how the data "
            "records a host whose shim is the plugin's own SKILL.md. "
            f"`install-host {host_id}` is --check-only."
        )
    return root / template


def snippets(base: Optional[str] = None) -> Dict[str, str]:
    """The shared shim partials, keyed by the slot spelling they fill.

    ``hosts/snippets/poll-loop.md`` fills ``{{poll_loop}}``. They are host
    independent by construction (a test asserts it), interpolated here rather than
    referenced, because a shim may not send an agent off to open a second file.
    """
    root = Path(str(base) if base else str(skill_dir())) / SNIPPET_DIR
    found: Dict[str, str] = {}
    if not root.is_dir():
        return found
    for path in sorted(root.glob("*.md")):
        slot = "{{" + path.stem.replace("-", "_") + "}}"
        found[slot] = path.read_text(encoding="utf-8")
    return found


def render(
    host_id: str,
    *,
    base: Optional[str] = None,
    skill: Optional[str] = None,
    template: Optional[str] = None,
) -> str:
    """The shim as an agent will read it — every slot filled, no header yet.

    *base* is the root the capability data, the template and the snippets are read
    from; *skill* is the absolute prefix baked into the result, defaulting to
    *base*. They differ only in tests, which render the shipped templates against a
    fixture skill dir containing a space while still reading the real data. At run
    time both are the running skill dir: ``os.path.abspath``, symlinks preserved
    (D1c). *template* renders text the caller already has, which is how the
    shipped-shim CI guard renders a file (including the one shim that has no
    template) through this exact function instead of a second implementation.
    """
    root = str(base) if base else str(skill_dir())
    prefix = str(skill) if skill else root
    text = template if template is not None else template_path(
        host_id, base
    ).read_text(encoding="utf-8")

    # Snippets first: a partial may itself carry the uv-message slot.
    partials = snippets(base)
    for _ in range(_MAX_SNIPPET_DEPTH):
        replaced = text
        for slot, body in partials.items():
            replaced = replaced.replace(slot, body)
        if replaced == text:
            break
        text = replaced

    for verb, slot in caps.VERB_SLOTS.items():
        text = text.replace(slot, caps.verb_sentence(host_id, verb, base))

    source = Path(root) / UV_MISSING_RELATIVE
    text = text.replace(
        SLOT_UV_MISSING_TEXT,
        source.read_text(encoding="utf-8").rstrip("\n")
        if source.is_file() else uv_missing_text(root),
    )
    # The *baked* path, so a shim that prints the message names the file where the
    # skill actually is rather than where it was read from.
    text = text.replace(
        SLOT_UV_MISSING_FILE, str(Path(prefix) / UV_MISSING_RELATIVE)
    )

    text = render_instruction_text(text, prefix)
    if not text.endswith("\n"):
        text += "\n"
    return text


def baked_prefix(text: str) -> Optional[str]:
    """The absolute skill dir a shim was rendered against, or ``None``.

    Read back out of the one place every shim carries it: the invariant
    ``uv run --project "<abs>"`` prefix. Quoted, so a path with spaces survives —
    and native Windows form, because it was computed inside a Python process
    (never an MSYS ``/c/…`` path a native Python cannot open).
    """
    match = re.search(r'uv run --project "([^"]+)"', text)
    if match:
        return match.group(1)
    match = re.search(r"uv run --project (\S+)", text)
    return match.group(1) if match else None


# ---------------------------------------------------------------------------
# The multi_llm_shim header
# ---------------------------------------------------------------------------

def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def body_of(text: str) -> str:
    """*text* with its header line removed — what the body hash is taken over.

    The header records the hash of the bytes as written, so it cannot include
    itself. Removing exactly the one line it occupies restores the rendered body
    byte-for-byte, which is what makes the re-hash on re-install meaningful.
    """
    lines = text.splitlines(keepends=True)
    kept = [line for line in lines if not _HEADER_RE.match(line)]
    return "".join(kept)


def parse_header(text: str) -> Optional[Dict[str, object]]:
    """The ``multi_llm_shim`` block, or ``None`` for a file that is not ours."""
    match = _HEADER_RE.search(text)
    if not match:
        return None
    try:
        payload = json.loads(match.group(1))
    except ValueError:
        return None
    return payload if isinstance(payload, dict) else None


def _header_line(host_id: str, entry: Dict[str, object], payload: Dict[str, object]) -> str:
    fmt = str(entry["shim"]["format"])
    opener, closer = _HEADER_SYNTAX.get(fmt, _HEADER_SYNTAX["markdown"])
    body = json.dumps(payload, sort_keys=True, separators=(", ", ": "))
    note = (
        f"{HEADER_KEY}: {body} — rendered by `multi_llm.py install-host "
        f"{host_id}`; edit the template in the skill, never this file, and re-run "
        "install-host after a plugin update."
    )
    return f"{opener}{note}{closer}\n"


def with_header(text: str, host_id: str, *, base: Optional[str] = None) -> str:
    """Insert the identifying header into a rendered body.

    Placed **after** the frontmatter when the host requires one: a leading comment
    before the opening ``---`` stops the host parsing the frontmatter at all.
    """
    entry = caps.entry(host_id, base)
    payload = {
        "host": host_id,
        "shim_version": SHIM_VERSION,
        "template_sha256": _template_sha(host_id, base),
        "body_sha256": _sha256(text),
    }
    line = _header_line(host_id, entry, payload)
    lines = text.splitlines(keepends=True)
    if lines and lines[0].strip() == "---":
        for index in range(1, len(lines)):
            if lines[index].strip() == "---":
                return "".join(lines[: index + 1]) + line + "".join(
                    lines[index + 1:]
                )
    return line + text


def _template_sha(host_id: str, base: Optional[str] = None) -> str:
    entry = caps.entry(host_id, base)
    if not entry["shim"]["template"]:
        return ""
    return _sha256(template_path(host_id, base).read_text(encoding="utf-8"))


def render_installed(host_id: str, *, base: Optional[str] = None) -> str:
    """The exact bytes ``install-host`` writes: rendered body plus header."""
    return with_header(render(host_id, base=base), host_id, base=base)


def local_edit(text: str) -> bool:
    """True when the file on disk no longer matches its own recorded body hash."""
    header = parse_header(text)
    if not header:
        return False
    return header.get("body_sha256") != _sha256(body_of(text))


def _is_pristine_shim(text: str) -> bool:
    """A shim of ours, byte-for-byte as it was written."""
    return parse_header(text) is not None and not local_edit(text)


# ---------------------------------------------------------------------------
# --check: exactly five assertions, in order
# ---------------------------------------------------------------------------

ROW_PRESENT = 1
ROW_PREFIX = 2
ROW_SHAPE = 3
ROW_GENERATION = 4
ROW_ENVIRONMENT = 5

ROW_NAMES: Dict[int, str] = {
    ROW_PRESENT: "present",
    ROW_PREFIX: "baked prefix current",
    ROW_SHAPE: "rendered shape valid",
    ROW_GENERATION: "generation current",
    ROW_ENVIRONMENT: "environment",
}

#: Windows needs Git Bash: every shim we write is a POSIX-shell command block, so
#: a Windows host without it would get a shim it cannot run. Same prerequisite the
#: README and ``references/uv-check.md`` state; no second detector.
GIT_BASH_MISSING = (
    "Git for Windows (Git Bash) is required on Windows: every command in a "
    "rendered shim is POSIX shell, and there is no PowerShell instruction path. "
    "Install it from https://git-scm.com/download/win and re-run."
)


@dataclass
class Row:
    number: int
    ok: bool
    detail: str
    fix: str = ""

    @property
    def name(self) -> str:
        return ROW_NAMES[self.number]


@dataclass
class CheckResult:
    host_id: str
    rows: List[Row] = field(default_factory=list)
    copies: List[Location] = field(default_factory=list)
    loaded: Optional[Location] = None
    notes: List[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return all(row.ok for row in self.rows)

    @property
    def failures(self) -> List[Row]:
        return [row for row in self.rows if not row.ok]

    def row(self, number: int) -> Optional[Row]:
        for row in self.rows:
            if row.number == number:
                return row
        return None


def repair_line(host_id: str, base: Optional[str] = None) -> str:
    """The one string a stale shim is repaired with, everywhere it is printed.

    The same string D1c's moved-skill-dir message and the README quickstart print:
    the instruction a user sees and the command that repairs are never two
    different things.
    """
    prefix = dispatcher_prefix(Path(str(base)) if base else None)
    return f"{prefix} install-host {host_id}"


def check(
    host_id: str,
    *,
    base: Optional[str] = None,
    env: Optional[Dict[str, str]] = None,
    project_root: Optional[Path] = None,
    path: Optional[Path] = None,
    windows: Optional[bool] = None,
) -> CheckResult:
    """Verify an install: five assertions, in order, each failing on its own.

    *path* pins the file to check (an install verifying what it just wrote);
    otherwise every location is searched and the copy the host would actually load
    is the one rows 2-4 are asserted against. A host whose shim is not ours to
    install (``installable: false``) runs rows 3-5 only: there is no file of ours
    to find (row 1) and no prefix we baked (row 2).
    """
    entry = caps.entry(host_id, base)
    result = CheckResult(host_id=host_id)
    installable = bool(entry["installable"])
    root = str(base) if base else str(skill_dir())

    subject: Optional[Path]
    if not installable:
        subject = Path(root) / entry["shim"]["installed"]
        result.notes.append(
            f"host '{host_id}' is not installable: its shim is the plugin's own "
            f"{entry['shim']['installed']}, which the host resolves itself. "
            "Rows 1-2 do not apply."
        )
    elif path is not None:
        subject = Path(path)
        result.copies = existing_copies(
            host_id, base=base, env=env, project_root=project_root
        )
        result.loaded = result.copies[0] if result.copies else None
        if subject.is_file():
            result.rows.append(Row(ROW_PRESENT, True, str(subject)))
        else:
            result.rows.append(
                Row(
                    ROW_PRESENT, False, f"{subject} is missing",
                    f"run `{repair_line(host_id, base)}`",
                )
            )
    else:
        result.copies = existing_copies(
            host_id, base=base, env=env, project_root=project_root
        )
        result.loaded = result.copies[0] if result.copies else None
        subject = result.loaded.path if result.loaded else None
        if subject is None:
            target = target_location(
                host_id, DEFAULT_SCOPE, base=base, env=env,
                project_root=project_root,
            )
            result.rows.append(
                Row(
                    ROW_PRESENT, False,
                    f"no shim found in any of {host_id}'s install paths",
                    f"run `{repair_line(host_id, base)}` (writes {target.path})",
                )
            )
        else:
            detail = f"{len(result.copies)} copy(ies); loads {subject}"
            result.rows.append(Row(ROW_PRESENT, True, detail))

    if subject is None or not subject.is_file():
        # Rows 2-4 read the file; without one they are unanswerable rather than
        # failed, and row 5 is still worth reporting.
        result.rows.append(_environment_row(host_id, base=base, windows=windows))
        return result

    text = subject.read_text(encoding="utf-8")

    if installable:
        result.rows.append(_prefix_row(host_id, text, root, base))
    result.rows.append(_shape_row(host_id, text, base))
    result.rows.append(_generation_row(host_id, text, base, installable))
    result.rows.append(_environment_row(host_id, base=base, windows=windows))

    if installable and local_edit(text):
        result.notes.append(
            f"{subject} has local edits (its body no longer matches the hash it "
            "records). Re-installing needs --force, which preserves the edited "
            "file as <shim>.local.bak."
        )
    if installable and str(entry["reload"]) != "none" and path is None:
        # An install prints this line itself, on success and once (see `install`);
        # a standalone check carries it as a note, because "installed but not yet
        # loaded" is a state a reader has to be told about either way.
        result.notes.append(reload_note(host_id, base))
    return result


def reload_note(host_id: str, base: Optional[str] = None) -> str:
    """The host's own reload requirement — a state, never a failure.

    "Installed but not yet loaded" is a distinct, non-failing condition: a
    file-scanning command host picks a new shim up on the next invocation, a host
    that enumerates skills at session start needs a fresh session, and the
    reference host takes a plugin update rather than an install.
    """
    entry = caps.entry(host_id, base)
    value = str(entry["reload"])
    if value == "none":
        return (
            f"host '{host_id}' needs no reload: its shim ships with the plugin, so "
            "a plugin update is the only refresh."
        )
    if value == "restart":
        return (
            f"[NOT_YET_LOADED] restart {host_id} before invoking the command; it "
            "reads its configuration once at startup."
        )
    return (
        f"[NOT_YET_LOADED] start a new {host_id} session before invoking the "
        "command; this host enumerates its commands/skills at session start."
    )


def _prefix_row(
    host_id: str, text: str, root: str, base: Optional[str]
) -> Row:
    prefix = baked_prefix(text)
    if not prefix:
        return Row(
            ROW_PREFIX, False,
            "the file carries no `uv run --project \"<abs>\"` prefix, so nothing "
            "binds it to a skill dir",
            f"run `{repair_line(host_id, base)}`",
        )
    if not Path(prefix).is_dir():
        return Row(
            ROW_PREFIX, False,
            f"the baked skill dir no longer exists: {prefix} (the plugin was "
            "updated or removed — the cache is keyed by commit hash)",
            f"run `{repair_line(host_id, base)}`",
        )
    if os.path.normcase(os.path.abspath(prefix)) != os.path.normcase(
        os.path.abspath(root)
    ):
        return Row(
            ROW_PREFIX, False,
            f"the baked skill dir moved: shim says {prefix}, running skill dir is "
            f"{root}",
            f"run `{repair_line(host_id, base)}`",
        )
    return Row(ROW_PREFIX, True, prefix)


def shape_problems(
    host_id: str, text: str, base: Optional[str] = None
) -> List[str]:
    """Row 3's list: does the file parse the way the shipped-shim guard parses it?

    Frontmatter where the host requires one, exactly one dispatcher command block,
    the uv preflight ahead of the first ``uv run``, no surviving placeholder or
    unfilled slot, the three verb sentences filled once each, and a baked
    ``--host`` id that is a key in the capability data.
    """
    entry = caps.entry(host_id, base)
    problems: List[str] = []
    fmt = str(entry["shim"]["format"])
    if fmt.endswith("+frontmatter"):
        lines = text.splitlines()
        if not lines or lines[0].strip() != "---" or "---" not in lines[1:]:
            problems.append(
                f"this host's shim format is {fmt}, but the file opens with no "
                "`---` frontmatter block"
            )
    forbidden = FORBIDDEN_IN_INSTALLED if entry["installable"] else tuple(
        token for token in FORBIDDEN_IN_INSTALLED
        if token != _HOST_EXPANDED_PLACEHOLDER
    )
    for token in forbidden:
        if token in text:
            problems.append(f"the placeholder {token} survived rendering")
    for slot in sorted(set(_SLOT_RE.findall(text))):
        problems.append(f"the slot {slot} was never filled")

    dispatchers = re.findall(r'multi_llm\.py"?\s+<mode>', text)
    if len(dispatchers) != 1:
        problems.append(
            f"expected exactly one dispatcher command block, found "
            f"{len(dispatchers)}"
        )
    probe = text.find("command -v uv")
    first_run = text.find("uv run --project")
    if probe < 0:
        problems.append("no `command -v uv` preflight")
    elif 0 <= first_run < probe:
        problems.append(
            "the uv preflight comes after the first `uv run`, so a missing uv "
            "surfaces as a bare `command not found`"
        )
    baked = set(re.findall(r"--host\s+([a-z][a-z0-9-]*)", text))
    if not baked:
        problems.append("no `--host <id>` is baked into the dispatcher command")
    elif baked != {host_id}:
        problems.append(
            f"the file bakes --host {sorted(baked)} but is the shim for "
            f"'{host_id}'"
        )
    else:
        known = caps.host_ids(base)
        for candidate in baked:
            if candidate not in known:
                problems.append(
                    f"the baked --host '{candidate}' is not a key in the "
                    "capability data"
                )
    for verb, sentence in zip(caps.VERBS, caps.verb_sentences(host_id, base)):
        if text.count(sentence) != 1:
            problems.append(
                f"the *{caps.VERB_WORDING[verb]}* resolution appears "
                f"{text.count(sentence)} times; exactly one per verb, byte-"
                "identical to the capability data's own render"
            )
    if bool(entry["installable"]) and "--yes" not in text:
        problems.append(
            "an installable shim never passes --yes; unattended is the default on "
            "every host that is not the interactive reference host"
        )
    return problems


def _shape_row(host_id: str, text: str, base: Optional[str]) -> Row:
    problems = shape_problems(host_id, text, base)
    if problems:
        return Row(
            ROW_SHAPE, False, "; ".join(problems),
            f"run `{repair_line(host_id, base)}` to re-render from the template",
        )
    return Row(ROW_SHAPE, True, "frontmatter, one dispatcher block, uv preflight, "
                                "no unfilled slot")


def _generation_row(
    host_id: str, text: str, base: Optional[str], installable: bool
) -> Row:
    if not installable:
        return Row(
            ROW_GENERATION, True,
            "n/a — this shim is not rendered, so it carries no generation",
        )
    header = parse_header(text)
    if header is None:
        return Row(
            ROW_GENERATION, False,
            f"no {HEADER_KEY} block: this file was not written by install-host "
            "(hand-authored, or from a copy of an older layout)",
            f"run `{repair_line(host_id, base)}`",
        )
    recorded = header.get("shim_version")
    if recorded != SHIM_VERSION:
        return Row(
            ROW_GENERATION, False,
            f"shim generated by an older multi-llm (shim_version {recorded!r}, "
            f"current {SHIM_VERSION})",
            f"run `{repair_line(host_id, base)}`",
        )
    return Row(ROW_GENERATION, True, f"shim_version {SHIM_VERSION}")


def _environment_row(
    host_id: str,
    *,
    base: Optional[str] = None,
    windows: Optional[bool] = None,
) -> Row:
    """Row 5 — the install-time half of the uv bootstrap (D6c layer 1).

    Layer 1 exists because layer 3 cannot run: every invocation goes through
    ``uv run``, so on a machine with no uv the shell fails with exit 127 before any
    Python could print the message. A host installed successfully has therefore
    already been told about uv, and no run reaches the 127 case.
    """
    entry = caps.entry(host_id, base)
    problems: List[str] = []
    details: List[str] = []
    uv = find_uv()
    if uv is None:
        problems.append(uv_missing_text(base))
    else:
        details.append(f"uv={uv}")

    runner = str(entry["default_subagent_runner"])
    provider = runner.split(":", 1)[0]
    if not runner_available(provider):
        problems.append(
            f"the runner CLI for this host's default subagent runner "
            f"'{runner}' is not installed, so every phase that dispatches a "
            f"subagent would fail. Install the '{provider}' CLI (or point "
            "`driver.subagent_runner` in providers.yaml at one you have) and "
            "re-check."
        )
    else:
        details.append(f"runner={runner}")

    is_windows = os.name == "nt" if windows is None else bool(windows)
    if is_windows:
        if shutil.which("bash") is None:
            problems.append(GIT_BASH_MISSING)
        else:
            details.append("bash=found")

    if problems:
        return Row(
            ROW_ENVIRONMENT, False, "; ".join(problems),
            "install the missing prerequisite named above, then re-run "
            f"`{repair_line(host_id, base)} --check`",
        )
    return Row(ROW_ENVIRONMENT, True, ", ".join(details))


def runner_available(provider: str) -> bool:
    """Is this provider's CLI installed?

    Reuses ``init_config``'s detection path — ``provider_registry.get_provider``
    plus the adapter's own ``is_available()`` — rather than re-implementing a
    second probe that could disagree with ``--init``.
    """
    try:
        try:
            from .provider_registry import get_provider
        except ImportError:  # pragma: no cover - direct script runs
            from provider_registry import get_provider  # type: ignore
        adapter = get_provider(provider)
    except Exception:  # pragma: no cover - a config error is not a check failure
        return False
    if adapter is None:
        return False
    try:
        return bool(adapter.is_available())
    except Exception:  # pragma: no cover - a probe that raises is a miss
        return False


