#!/usr/bin/env python3
"""Render ``references/host-capabilities.md`` from ``hosts/capabilities.yaml`` (D5b).

The capability matrix is **data with a schema, and the markdown is a build
artifact**. Keeping a prose table by hand would leave the shims,
``install-host --check`` and the tests each re-encoding the same facts, and would
put a table an agent might read back on the read path.

The generated document has a **fixed shape, not an authored one**: one row per host
with the columns the design names, followed by one short per-host section carrying
only the free-form ``notes`` strings and that host's ``env_guards`` names — the one
place a reader can see which variables get stripped from a dispatched runner.
Nothing hand-written survives a render, which is what makes the byte-compare
meaningful rather than a formatting lottery.

The **README's "Hosting multi-llm in other harnesses" section is generated by this
same script** (D7), between two markers, for exactly the reason the reference
document is: a hand-maintained second copy of the matrix is a copy that goes stale,
and ``--check`` fails CI when either file differs from a fresh render.

Usage::

    python hosts/render_capabilities.py            # write both generated files
    python hosts/render_capabilities.py --check     # exit 1 if either copy is stale
    python hosts/render_capabilities.py --stdout    # print the reference doc, write nothing
    python hosts/render_capabilities.py --stdout --readme   # print the README block
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

SKILL_ROOT = Path(os.path.abspath(__file__)).parent.parent
sys.path.insert(0, str(SKILL_ROOT))

from utils import host_capabilities as caps  # noqa: E402
from utils.stream_bootstrap import bootstrap_streams  # noqa: E402

#: Where the rendered document lands. A ``references/*.md`` file, and therefore
#: exempt from the host-neutrality lint: naming host tools is its whole job.
OUTPUT = os.path.join("references", "host-capabilities.md")

_HEADER = """<!-- GENERATED FILE — DO NOT EDIT.
     Rendered from hosts/capabilities.yaml by hosts/render_capabilities.py.
     Edit the YAML and re-render; CI fails if this file differs from a fresh
     render, so a hand-edit cannot ship. -->

# Host capabilities

Human-readable view of `hosts/capabilities.yaml`. **Nothing reads this file at run
time** — not an orchestrator, not a shim, and above all not a driving agent. The
YAML is consumed by `multi_llm.py`, by `install-host` and by the tests; this
document exists for people reading the repo.

Every value carries a **provenance**: `verified` means a recorded live smoke run
observed it, `documented` means host docs only, `unknown` is the shipping default.
A `documented`-only value never selects the non-conservative path — which is why
hosts whose native subagent dispatch is merely documented ship as
`subagents: executor`, and why a documented command-timeout ceiling is worked
around with `--detach` rather than trusted.

The three **capability verbs** are the spine of each entry. The host-neutral
instruction core says *spawn subagents* / *ask the user* / *run detached*; the
columns below say what each resolves to, and a shim bakes that resolution in as a
sentence when it is installed.
"""

_MATRIX_HEAD = [
    "| Host | Shim (repo → installed) | `arguments` | *spawn subagents* | "
    "*ask the user* | *run detached* | Default runner | `nested_exec` "
    "(spawn/network/creds) | Max subagents | Timeout ceiling | Verified |",
    "|---|---|---|---|---|---|---|---|---|---|---|",
]


def _verb_cell(host: Dict[str, Any], verb: str) -> str:
    value = str(host[verb])
    tool = (host.get("native_tool") or {}).get(verb)
    provenance = host["provenance"].get(verb, "unknown")
    cell = f"`{value}`"
    if tool:
        cell += f" (`{tool}`)"
    return f"{cell} — {provenance}"


def _shim_cell(host: Dict[str, Any]) -> str:
    shim = host["shim"]
    template = shim.get("template")
    installed = shim["installed"]
    if template is None:
        return f"*not rendered* → `{installed}`"
    return f"`{template}` → `{installed}`"


def _timeout_cell(host: Dict[str, Any]) -> str:
    ceiling = host["timeout_ceiling_s"]
    if not ceiling:
        return "none documented"
    override = host["timeout_override"]
    channels = [
        f"{name}: `{value}`"
        for name, value in override.items()
        if value != "none"
    ]
    raised = ", ".join(channels) if channels else "not raisable"
    return f"{ceiling} s (raise via {raised})"


def _verified_cell(host: Dict[str, Any]) -> str:
    verified = sorted(
        field for field, value in host["provenance"].items() if value == "verified"
    )
    return ", ".join(f"`{f}`" for f in verified) if verified else "*none yet*"


def _matrix(hosts: Dict[str, Any]) -> List[str]:
    rows = list(_MATRIX_HEAD)
    for host_id in sorted(hosts):
        host = hosts[host_id]
        rows.append(
            "| `{id}` | {shim} | `{args}` | {sub} | {ask} | {det} | `{runner}` | "
            "{nested} | {maxc} | {timeout} | {verified} |".format(
                id=host_id,
                shim=_shim_cell(host),
                args=host["arguments"],
                sub=_verb_cell(host, "subagents"),
                ask=_verb_cell(host, "ask"),
                det=_verb_cell(host, "detach"),
                runner=host["default_subagent_runner"],
                nested="/".join(
                    str(host["nested_exec"][key])
                    for key in ("spawn", "network", "credentials")
                ),
                maxc=host["max_concurrent_subagents"],
                timeout=_timeout_cell(host),
                verified=_verified_cell(host),
            )
        )
    return rows


def _sections(hosts: Dict[str, Any]) -> List[str]:
    lines: List[str] = ["", "## Per-host notes and stripped variables", ""]
    for host_id in sorted(hosts):
        host = hosts[host_id]
        lines.append(f"### `{host_id}`")
        lines.append("")
        lines.append(
            f"- Installable: `{str(host['installable']).lower()}`; "
            f"reload after install: `{host['reload']}`; "
            f"multi-turn session: `{str(host['multi_turn']).lower()}`"
        )
        tiers = host["subagent_tiers"]
        if tiers is None:
            lines.append(
                "- Subagent tiers: resolved from `providers.yaml` "
                "`driver.subagent_runner{,_cheap}` (this host does not dispatch "
                "subagents natively)"
            )
        else:
            cheap = tiers.get("cheap", tiers["full"])
            lines.append(
                f"- Subagent tiers: full `{tiers['full']}`, cheap `{cheap}`"
            )
        lines.append("- Verb sentences a rendered shim carries:")
        for sentence in caps.verb_sentences(host_id):
            lines.append(f"  - {sentence}")
        for scope in ("project", "global", "legacy"):
            paths = host["install_paths"][scope]
            rendered = ", ".join(f"`{p}`" for p in paths) if paths else "*none*"
            lines.append(f"- Install paths ({scope}): {rendered}")
        runners = host["runners"]
        lines.append("- Runners:")
        for name in sorted(runners):
            spec = runners[name]
            lines.append(
                f"  - `{name}`: bundled=`{str(spec['bundled']).lower()}`, "
                f"needs_auth=`{str(spec['needs_auth']).lower()}`"
                + (f" (`{spec['login_cmd']}`)" if spec["login_cmd"] else "")
                + f", profiles=[{', '.join(spec['profiles'])}]"
                + f", usage=`{spec['usage']}`"
            )
        guards = host["env_guards"]
        for key, label in (
            ("guards", "Refuse-to-start guards stripped from a dispatched runner"),
            ("session_scoped", "Session-scoping variables stripped"),
            ("passthrough", "Sanctioned exceptions that survive stripping"),
        ):
            names = guards[key]
            rendered = ", ".join(f"`{n}`" for n in names) if names else (
                "*none recorded* — "
                + (
                    "audited, found nothing"
                    if host["provenance"]["env_guards"] != "unknown"
                    else "the env diff has not run yet"
                )
            )
            lines.append(f"- {label}: {rendered}")
        notes = host["nested_exec"]["notes"].strip()
        if notes:
            lines.append(f"- Nested-exec notes: {' '.join(notes.split())}")
        lines.append("")
    return lines


def render(base: Optional[str] = None) -> str:
    """The whole document, deterministically ordered."""
    hosts = caps.load(base).get("hosts", {})
    body = [_HEADER, ""]
    body += _matrix(hosts)
    body += _sections(hosts)
    return "\n".join(body).rstrip("\n") + "\n"


# ---------------------------------------------------------------------------
# The README section (D7) — generated, never hand-maintained
# ---------------------------------------------------------------------------

#: Repo (and published-plugin) root, relative to the skill: the README sits beside
#: `.claude-plugin/`, two levels up from `skills/multi-llm/`.
README = "README.md"

#: The block this script owns. Everything between the markers is regenerated; the
#: markers themselves are the only hand-written part, and the ``--check`` guard is
#: what keeps a hand-edit inside them from shipping.
README_BEGIN = "<!-- BEGIN GENERATED: host-install (hosts/render_capabilities.py) -->"
README_END = "<!-- END GENERATED: host-install -->"


def readme_path() -> Path:
    return SKILL_ROOT.parent.parent / README


def _install_path_cell(paths: List[str]) -> str:
    return ", ".join(f"`{p}`" for p in paths) if paths else "—"


def _reload_sentence(host_id: str, host: Dict[str, Any]) -> str:
    value = str(host["reload"])
    if value == "none":
        return (
            "no reload step — this shim ships with the plugin, so a plugin update "
            "is the refresh"
        )
    if value == "restart":
        return f"restart {host_id} afterwards (it reads its config once, at startup)"
    return (
        f"start a new {host_id} session afterwards (it enumerates its "
        "commands/skills at session start)"
    )


def render_readme_section(base: Optional[str] = None) -> str:
    """The README block, generated from the same data as everything else."""
    hosts = caps.load(base).get("hosts", {})
    installable = [h for h in sorted(hosts) if hosts[h]["installable"]]
    lines: List[str] = [
        "## Hosting multi-llm in other harnesses",
        "",
        "The workflow itself is host-neutral: the instruction core names three "
        "capability *verbs* (*spawn subagents*, *ask the user*, *run detached*) "
        "and no tool, and one dispatcher command runs every mode. What a host "
        "needs is therefore just an **entry shim** — a small file, in that host's "
        "own command/skill format, with this skill's absolute path and its "
        "`--host` id baked in. `install-host` renders and writes it:",
        "",
        "```bash",
        "# from anywhere; SKILL is the installed skill directory",
        'uv run --project "$SKILL" -- python "$SKILL/multi_llm.py" install-host '
        "<host> [--global|--project]",
        "```",
        "",
        "It writes a **rendered copy** — never a symlink or junction, so nothing "
        "here needs symlink privileges on Windows — atomically, then verifies what "
        "it wrote and rolls back if the verification fails. `--check` re-runs that "
        "verification on its own: shim present (every copy found, in the host's "
        "discovery order, naming the one that loads), baked skill-dir prefix still "
        "current, rendered shape valid, shim generation current, and `uv` plus the "
        "host's runner CLI resolvable.",
        "",
        "### Per-host quickstart",
        "",
    ]
    for host_id in installable:
        host = hosts[host_id]
        lines += [
            f"**`{host_id}`**",
            "",
            "```bash",
            f"uv run --project \"$SKILL\" -- python \"$SKILL/multi_llm.py\" "
            f"install-host {host_id}            # machine-wide",
            f"uv run --project \"$SKILL\" -- python \"$SKILL/multi_llm.py\" "
            f"install-host {host_id} --project  # just this repository",
            f"uv run --project \"$SKILL\" -- python \"$SKILL/multi_llm.py\" "
            f"install-host {host_id} --check    # verify an install",
            "```",
            "",
            f"Writes `{host['install_paths']['global'][0]}/"
            f"{os.path.basename(host['shim']['installed'])}`"
            + (
                " (whose `$XDG_CONFIG_HOME` falls back to `~/.config` when unset)"
                if "XDG_CONFIG_HOME" in host["install_paths"]["global"][0]
                else ""
            )
            + f" (`--project`: `{host['install_paths']['project'][0]}/"
            f"{os.path.basename(host['shim']['installed'])}`), then "
            f"{_reload_sentence(host_id, host)}. Invoke it as `/multi-llm "
            "<the same arguments the Claude Code skill takes>`; unattended is the "
            "default on every host but Claude Code, so `--yes` is baked in.",
            "",
        ]
    lines += [
        "### Capability matrix",
        "",
        "Generated from `skills/multi-llm/hosts/capabilities.yaml` — the same data "
        "`install-host` renders a shim from. Every value carries a **provenance**: "
        "`verified` means a recorded live run observed it, `documented` means host "
        "docs only, `unknown` is the shipping default, and a `documented`-only "
        "value never selects the non-conservative path (which is why hosts whose "
        "native subagent dispatch is merely documented ship as `executor`).",
        "",
        "| Host | Installable | Command format | Args | *spawn subagents* | "
        "*ask the user* | *run detached* | Default runner | Reload |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for host_id in sorted(hosts):
        host = hosts[host_id]
        lines.append(
            "| `{id}` | {inst} | `{fmt}` | `{args}` | {sub} | {ask} | {det} | "
            "`{runner}` | `{reload}` |".format(
                id=host_id,
                inst="yes" if host["installable"] else "no (ships with the plugin)",
                fmt=host["shim"]["format"],
                args=host["arguments"],
                sub=_verb_cell(host, "subagents"),
                ask=_verb_cell(host, "ask"),
                det=_verb_cell(host, "detach"),
                runner=host["default_subagent_runner"],
                reload=host["reload"],
            )
        )
    lines += [
        "",
        "### Where the shim goes",
        "",
        "One row per host **and scope**, not one path per host. `install-host` "
        "writes only the preferred path of the scope you asked for; it *detects and "
        "reports* the rest, so an existing install is upgraded rather than silently "
        "shadowed. Compatibility locations stay valid inputs and are never written: "
        "migrating is re-run `install-host`, then delete the file it names. `~` is "
        "`%USERPROFILE%` on Windows and the XDG roots honour `$XDG_CONFIG_HOME`; "
        "the tokens below are what the data stores.",
        "",
        "| Host | Global (preferred) | Project (preferred) | "
        "Compatibility (detected, never written) |",
        "|---|---|---|---|",
    ]
    for host_id in sorted(hosts):
        host = hosts[host_id]
        paths = host["install_paths"]
        if not host["installable"]:
            lines.append(
                f"| `{host_id}` | *n/a* — the plugin's own "
                f"`{host['shim']['installed']}` | *n/a* | "
                f"{_install_path_cell(paths['project'] + paths['global'])} "
                "(non-plugin install) |"
            )
            continue
        lines.append(
            f"| `{host_id}` | {_install_path_cell(paths['global'])} | "
            f"{_install_path_cell(paths['project'])} | "
            f"{_install_path_cell(paths['legacy'])} |"
        )
    lines += [
        "",
        "### After a plugin update",
        "",
        "A plugin update **changes the skill directory path** — the Claude plugin "
        "cache is keyed by commit hash — so every installed shim's baked prefix "
        "goes stale. That is the common case, not an edge case, and it is one "
        "command:",
        "",
        "```bash",
        'uv run --project "$SKILL" -- python "$SKILL/multi_llm.py" install-host '
        "--check --all   # what moved",
        'uv run --project "$SKILL" -- python "$SKILL/multi_llm.py" install-host '
        "--all           # re-render every installed shim",
        "```",
        "",
        "Repair is always re-render, never in-place patching, and a re-install with "
        "nothing changed is byte-identical and does nothing. A shim you edited by "
        "hand is **never** overwritten silently: the install stops and names the "
        "file, and `--force` keeps your version as `<shim>.local.bak`. The inverse "
        "is `uninstall-host <host> [--global|--project|--all] [--dry-run]`, which "
        "removes only files carrying our `multi_llm_shim` block — identified by "
        "that block, never by filename.",
    ]
    return "\n".join(lines) + "\n"


def readme_with_section(current: str, base: Optional[str] = None) -> str:
    """*current* README with the generated block replaced (markers preserved)."""
    section = render_readme_section(base)
    block = f"{README_BEGIN}\n\n{section}\n{README_END}"
    start = current.find(README_BEGIN)
    end = current.find(README_END)
    if start < 0 or end < 0:
        raise SystemExit(
            f"ERROR: {README} carries no generated-host-install markers. Add\n"
            f"  {README_BEGIN}\n  {README_END}\n"
            "where the section belongs, then re-run this script."
        )
    return current[:start] + block + current[end + len(README_END):]


def main(argv: Optional[Sequence[str]] = None) -> int:
    bootstrap_streams()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true",
        help="Exit 1 if either generated copy differs from a fresh render "
             "(the CI staleness guard).",
    )
    parser.add_argument(
        "--stdout", action="store_true", help="Print the render; write nothing."
    )
    parser.add_argument(
        "--readme", action="store_true",
        help="Operate on the README's generated host-install section instead of "
             "references/host-capabilities.md.",
    )
    args = parser.parse_args(list(argv) if argv is not None else None)

    if args.stdout:
        sys.stdout.write(
            render_readme_section() if args.readme else render()
        )
        return 0

    text = render()
    target = SKILL_ROOT / OUTPUT
    readme = readme_path()
    if args.check:
        failures = []
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != text:
            failures.append(OUTPUT)
        if readme.is_file():
            body = readme.read_text(encoding="utf-8")
            if readme_with_section(body) != body:
                failures.append(README)
        if not failures:
            print(f"{OUTPUT} and {README} are up to date.")
            return 0
        print(
            f"ERROR: {', '.join(failures)} stale. Generated from "
            "hosts/capabilities.yaml — re-run `python "
            "hosts/render_capabilities.py` and commit the result.",
            file=sys.stderr,
        )
        return 1
    if not args.readme:
        target.write_text(text, encoding="utf-8")
        print(f"wrote {OUTPUT}")
    if readme.is_file():
        body = readme.read_text(encoding="utf-8")
        readme.write_text(readme_with_section(body), encoding="utf-8")
        print(f"wrote {README} (generated host-install section)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
