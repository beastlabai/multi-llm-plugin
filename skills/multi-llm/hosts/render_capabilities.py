#!/usr/bin/env python3
"""Render ``references/host-capabilities.md`` from ``hosts/capabilities.yaml`` (D5b).

The capability matrix is **data with a schema, and the markdown is a build
artifact**. Keeping a prose table by hand would leave the shims,
``install-host --check`` and the tests each re-encoding the same facts, and would
put a table an agent might read back on the read path.

The generated document has a **fixed shape, not an authored one**: one row per host
with the columns the design names, followed by one short per-host section carrying
only the free-form ``notes`` strings and that host's ``env_guards`` names — the one
place a reader can see which variables get stripped from a dispatched runner.
Nothing hand-written survives a render, which is what makes the byte-compare
meaningful rather than a formatting lottery.

The **"Hosting multi-llm in other harnesses" section of ``docs/hosts.md`` is
generated by this same script** (D7), between two markers, for exactly the reason
the reference document is: a hand-maintained second copy of the matrix is a copy
that goes stale, and ``--check`` fails CI when either file differs from a fresh
render. That section used to live in the repo ``README.md``; it moved out when the
README was trimmed to a front page, and only the target path changed.

**A missing host doc is stale, not absent**: ``--check`` fails when
``docs/hosts.md`` does not exist or has lost its markers, and so does a write —
this script fills in the block between the two markers and never creates the
page, because the header above and the footer below them are hand-written. The
bootstrap is therefore: create ``docs/hosts.md`` with both markers plus that
header and footer, then run this script to fill the block.

Usage::

    python hosts/render_capabilities.py            # write both generated files
    python hosts/render_capabilities.py --check     # exit 1 if either copy is stale
    python hosts/render_capabilities.py --stdout    # print the reference doc, write nothing
    python hosts/render_capabilities.py --stdout --host-doc  # print the docs/hosts.md block
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

SKILL_ROOT = Path(os.path.abspath(__file__)).parent.parent
sys.path.insert(0, str(SKILL_ROOT))

from utils import host_capabilities as caps  # noqa: E402
from utils.stream_bootstrap import bootstrap_streams  # noqa: E402

#: Where the rendered document lands. A ``references/*.md`` file, and therefore
#: exempt from the host-neutrality lint: naming host tools is its whole job.
OUTPUT = os.path.join("references", "host-capabilities.md")

_HEADER = """<!-- GENERATED FILE — DO NOT EDIT.
     Rendered from hosts/capabilities.yaml by hosts/render_capabilities.py.
     Edit the YAML and re-render; CI fails if this file differs from a fresh
     render, so a hand-edit cannot ship. -->

# Host capabilities

Human-readable view of `hosts/capabilities.yaml`. **Nothing reads this file at run
time** — not an orchestrator, not a shim, and above all not a driving agent. The
YAML is consumed by `multi_llm.py`, by `install-host` and by the tests; this
document exists for people reading the repo.

Every value carries a **provenance**: `verified` means a recorded live smoke run
observed it, `documented` means host docs only, `unknown` is the shipping default.
A `documented`-only value never selects the non-conservative path — which is why
hosts whose native subagent dispatch is merely documented ship as
`subagents: executor`, and why a documented command-timeout ceiling is worked
around with `--detach` rather than trusted.

The three **capability verbs** are the spine of each entry. The host-neutral
instruction core says *spawn subagents* / *ask the user* / *run detached*; the
columns below say what each resolves to, and a shim bakes that resolution in as a
sentence when it is installed.
"""

_MATRIX_HEAD = [
    "| Host | Shim (repo → installed) | `arguments` | *spawn subagents* | "
    "*ask the user* | *run detached* | Default runner | `nested_exec` "
    "(spawn/network/creds) | Max subagents | Timeout ceiling | Verified |",
    "|---|---|---|---|---|---|---|---|---|---|---|",
]


def _verb_cell(host: Dict[str, Any], verb: str) -> str:
    value = str(host[verb])
    tool = (host.get("native_tool") or {}).get(verb)
    provenance = host["provenance"].get(verb, "unknown")
    cell = f"`{value}`"
    if tool:
        cell += f" (`{tool}`)"
    return f"{cell} — {provenance}"


def _shim_cell(host: Dict[str, Any]) -> str:
    shim = host["shim"]
    template = shim.get("template")
    installed = shim["installed"]
    if template is None:
        return f"*not rendered* → `{installed}`"
    return f"`{template}` → `{installed}`"


def _timeout_cell(host: Dict[str, Any]) -> str:
    ceiling = host["timeout_ceiling_s"]
    if not ceiling:
        return "none documented"
    override = host["timeout_override"]
    channels = [
        f"{name}: `{value}`"
        for name, value in override.items()
        if value != "none"
    ]
    if not channels:
        return f"{ceiling} s (not raisable)"
    return f"{ceiling} s (raise via {', '.join(channels)})"


def _verified_cell(host: Dict[str, Any]) -> str:
    verified = sorted(
        field for field, value in host["provenance"].items() if value == "verified"
    )
    return ", ".join(f"`{f}`" for f in verified) if verified else "*none yet*"


def _matrix(hosts: Dict[str, Any], base: Optional[str] = None) -> List[str]:
    rows = list(_MATRIX_HEAD)
    for host_id in sorted(hosts):
        host = hosts[host_id]
        rows.append(
            "| `{id}` | {shim} | `{args}` | {sub} | {ask} | {det} | `{runner}` | "
            "{nested} | {maxc} | {timeout} | {verified} |".format(
                id=host_id,
                shim=_shim_cell(host),
                args=host["arguments"],
                sub=_verb_cell(host, "subagents"),
                ask=_verb_cell(host, "ask"),
                det=_verb_cell(host, "detach"),
                runner=host["default_subagent_runner"],
                nested="/".join(
                    str(host["nested_exec"][key])
                    for key in ("spawn", "network", "credentials")
                ),
                maxc=host["max_concurrent_subagents"],
                timeout=_timeout_cell(host),
                verified=_verified_cell(host),
            )
        )
    return rows


def _sections(hosts: Dict[str, Any], base: Optional[str] = None) -> List[str]:
    lines: List[str] = ["", "## Per-host notes and stripped variables", ""]
    for host_id in sorted(hosts):
        host = hosts[host_id]
        lines.append(f"### `{host_id}`")
        lines.append("")
        lines.append(
            f"- Installable: `{str(host['installable']).lower()}`; "
            f"reload after install: `{host['reload']}`"
        )
        lines.append(
            f"- Invocation ({host['provenance']['invocation']}): invoke it "
            f"{host['invocation']}"
        )
        lines.append(
            "- Driving agent gets a turn after a command returns "
            f"(`multi_turn`): `{str(host['multi_turn']).lower()}` — "
            f"{host['provenance']['multi_turn']}. A `false` here is what "
            "addresses a failed batch's retry instruction to the human rather "
            "than to an agent that will never read it."
        )
        tiers = host["subagent_tiers"]
        if tiers is None:
            lines.append(
                "- Subagent tiers: resolved from `providers.yaml` "
                "`driver.subagent_runner{,_cheap}` (this host does not dispatch "
                "subagents natively)"
            )
        else:
            cheap = tiers.get("cheap", tiers["full"])
            lines.append(
                f"- Subagent tiers: full `{tiers['full']}`, cheap `{cheap}`"
            )
        lines.append("- Verb sentences a rendered shim carries:")
        for sentence in caps.verb_sentences(host_id, base):
            lines.append(f"  - {sentence}")
        for scope in ("project", "global", "legacy"):
            paths = host["install_paths"][scope]
            rendered = ", ".join(f"`{p}`" for p in paths) if paths else "*none*"
            lines.append(f"- Install paths ({scope}): {rendered}")
        runners = host["runners"]
        lines.append("- Runners:")
        for name in sorted(runners):
            spec = runners[name]
            lines.append(
                f"  - `{name}`: bundled=`{str(spec['bundled']).lower()}`, "
                f"needs_auth=`{str(spec['needs_auth']).lower()}`"
                + (f" (`{spec['login_cmd']}`)" if spec["login_cmd"] else "")
                + f", profiles=[{', '.join(spec['profiles'])}]"
                + f", usage=`{spec['usage']}`"
            )
        guards = host["env_guards"]
        for key, label in (
            ("guards", "Refuse-to-start guards stripped from a dispatched runner"),
            ("session_scoped", "Session-scoping variables stripped"),
            ("passthrough", "Sanctioned exceptions that survive stripping"),
        ):
            names = guards[key]
            rendered = ", ".join(f"`{n}`" for n in names) if names else (
                "*none recorded* — "
                + (
                    "audited, found nothing"
                    if host["provenance"]["env_guards"] != "unknown"
                    else "the env diff has not run yet"
                )
            )
            lines.append(f"- {label}: {rendered}")
        notes = host["nested_exec"]["notes"].strip()
        if notes:
            lines.append(f"- Nested-exec notes: {' '.join(notes.split())}")
        lines.append("")
    return lines


def render(base: Optional[str] = None) -> str:
    """The whole document, deterministically ordered."""
    hosts = caps.load(base).get("hosts", {})
    body = [_HEADER, ""]
    body += _matrix(hosts, base)
    body += _sections(hosts, base)
    return "\n".join(body).rstrip("\n") + "\n"


# ---------------------------------------------------------------------------
# The host-install document (D7) — generated, never hand-maintained
# ---------------------------------------------------------------------------

#: Where the generated host-install section lands, relative to the repo (and
#: published-plugin) root — the directory holding `.claude-plugin/`, two levels up
#: from `skills/multi-llm/`. The markers, not the filename, are what this script
#: keys on, so moving the section again is a one-line change here.
HOST_DOC = os.path.join("docs", "hosts.md")

#: The block this script owns. Everything between the markers is regenerated; the
#: markers themselves are the only hand-written part, and the ``--check`` guard is
#: what keeps a hand-edit inside them from shipping.
HOST_DOC_BEGIN = "<!-- BEGIN GENERATED: host-install (hosts/render_capabilities.py) -->"
HOST_DOC_END = "<!-- END GENERATED: host-install -->"


def host_doc_path() -> Path:
    return SKILL_ROOT.parent.parent / HOST_DOC


def _install_path_cell(paths: List[str]) -> str:
    return ", ".join(f"`{p}`" for p in paths) if paths else "—"


def _reload_sentence(host_id: str, host: Dict[str, Any]) -> str:
    value = str(host["reload"])
    if value == "none":
        return (
            "no reload step — this shim ships with the plugin, so a plugin update "
            "is the refresh"
        )
    if value == "restart":
        return f"restart {host_id} afterwards (it reads its config once, at startup)"
    return (
        f"start a new {host_id} session afterwards (it enumerates its "
        "commands/skills at session start)"
    )


def _installable_prose(host_ids: List[str]) -> str:
    """The installable hosts in prose: `a`, then `a` and `b`, then `a`, `b` and `c`.

    Read off the same list the quickstarts iterate, so a host added to the data
    joins the opening sentence on the day it is added rather than leaving a
    hand-written "Codex and OpenCode" behind to go stale.

    Its contract is the *list of host names*, never the sentence around them —
    which is why the empty case returns a bare noun phrase and why
    :func:`_opening_sentence` does not use it there: interpolating "no other
    host yet" into "runs unchanged inside … as well" states something false,
    and the repair belongs to the sentence, not to this helper.
    """
    marks = [f"`{host_id}`" for host_id in host_ids]
    if len(marks) <= 1:
        return marks[0] if marks else "no other host yet"
    return f"{', '.join(marks[:-1])} and {marks[-1]}"


def _opening_sentence(host_ids: List[str]) -> str:
    """The host doc's first sentence — one shape per arity, all four true.

    With at least one installable host it is the D4 sentence, with the host
    list rendered by :func:`_installable_prose` so a fourth host joins it from
    the data alone. With **none** it is a different sentence rather than the
    same one with an empty slot: flipping every ``installable:`` in
    ``hosts/capabilities.yaml`` to ``false`` is a data-only change, and it must
    not be able to ship "it runs unchanged inside no other host yet as well".
    """
    if not host_ids:
        return (
            "multi-llm ships as a Claude Code plugin; no other host is "
            "installable yet."
        )
    return (
        "multi-llm ships as a Claude Code plugin, and it runs unchanged inside "
        f"{_installable_prose(host_ids)} as well."
    )


def render_host_doc_section(base: Optional[str] = None) -> str:
    """The `docs/hosts.md` block, generated from the same data as everything else."""
    hosts = caps.load(base).get("hosts", {})
    installable = [h for h in sorted(hosts) if hosts[h]["installable"]]
    lines: List[str] = [
        "# Hosting multi-llm in other harnesses",
        "",
        f"{_opening_sentence(installable)} The workflow itself is "
        "host-neutral: the instruction core names three capability *verbs* "
        "(*spawn subagents*, *ask the user*, *run detached*) and no tool, and one "
        "dispatcher command runs every mode. What a host needs is therefore just "
        "an **entry shim** — a small file, in that host's own command/skill "
        "format, with this skill's absolute path and its `--host` id baked in. "
        "`install-host` renders and writes it:",
        "",
        "```bash",
        "# from anywhere; SKILL is this skill tree on disk",
        'uv run --project "$SKILL" -- python "$SKILL/multi_llm.py" install-host '
        "<host> [--global|--project]",
        "```",
        "",
        "`SKILL` is either a git checkout of this repository or the plugin "
        "install `claude plugin list --json` reports; the README's "
        "[Codex and OpenCode](../README.md#codex-and-opencode) block resolves "
        "it, with a `jq`-free fallback for machines without a JSON parser.",
        "",
        "It writes a **rendered copy** — never a symlink or junction, so nothing "
        "here needs symlink privileges on Windows — atomically, then verifies what "
        "it wrote and rolls back if the verification fails. `--check` re-runs that "
        "verification on its own: shim present (every copy found, in the host's "
        "discovery order, naming the one that loads), baked skill-dir prefix still "
        "current, rendered shape valid, shim generation current, and `uv` plus the "
        "host's runner CLI resolvable.",
        "",
        "## Per-host quickstart",
        "",
    ]
    for host_id in installable:
        host = hosts[host_id]
        lines += [
            f"**`{host_id}`**",
            "",
            "```bash",
            f"uv run --project \"$SKILL\" -- python \"$SKILL/multi_llm.py\" "
            f"install-host {host_id}            # machine-wide",
            f"uv run --project \"$SKILL\" -- python \"$SKILL/multi_llm.py\" "
            f"install-host {host_id} --project  # just this repository",
            f"uv run --project \"$SKILL\" -- python \"$SKILL/multi_llm.py\" "
            f"install-host {host_id} --check    # verify an install",
            "```",
            "",
            f"Writes `{host['install_paths']['global'][0]}/"
            f"{os.path.basename(host['shim']['installed'])}`"
            + (
                " (whose `$XDG_CONFIG_HOME` falls back to `~/.config` when unset)"
                if "XDG_CONFIG_HOME" in host["install_paths"]["global"][0]
                else ""
            )
            + f" (`--project`: `{host['install_paths']['project'][0]}/"
            f"{os.path.basename(host['shim']['installed'])}`), then "
            f"{_reload_sentence(host_id, host)}. Invoke it "
            # Per host, from the data: the two installable hosts do NOT take the
            # same spelling. A constant here published `/multi-llm …` for codex,
            # whose composer answers it with "Unrecognized command" — measured
            # 2026-08-24, and the reason this reads `invocation` instead.
            f"{host['invocation']} Unattended is the default on every host but "
            "Claude Code, so `--yes` is baked in.",
            "",
        ]
        # Only where the obvious headless form is wrong in a way that fails
        # confusingly rather than loudly — see the field's schema description.
        if host.get("headless_invocation"):
            lines += [
                f"Headless, the argument list needs the host's own separator: "
                f"`{host['headless_invocation']}`.",
                "",
            ]
    lines += [
        "## Capability matrix",
        "",
        "Generated from `skills/multi-llm/hosts/capabilities.yaml` — the same data "
        "`install-host` renders a shim from. Every value carries a **provenance**: "
        "`verified` means a recorded live run observed it, `documented` means host "
        "docs only, `unknown` is the shipping default, and a `documented`-only "
        "value never selects the non-conservative path (which is why hosts whose "
        "native subagent dispatch is merely documented ship as `executor`).",
        "",
        "| Host | Installable | Command format | Args | *spawn subagents* | "
        "*ask the user* | *run detached* | Default runner | Reload |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for host_id in sorted(hosts):
        host = hosts[host_id]
        lines.append(
            "| `{id}` | {inst} | `{fmt}` | `{args}` | {sub} | {ask} | {det} | "
            "`{runner}` | `{reload}` |".format(
                id=host_id,
                inst="yes" if host["installable"] else "no (ships with the plugin)",
                fmt=host["shim"]["format"],
                args=host["arguments"],
                sub=_verb_cell(host, "subagents"),
                ask=_verb_cell(host, "ask"),
                det=_verb_cell(host, "detach"),
                runner=host["default_subagent_runner"],
                reload=host["reload"],
            )
        )
    lines += [
        "",
        "## Where the shim goes",
        "",
        "One row per host **and scope**, not one path per host. `install-host` "
        "writes only the preferred path of the scope you asked for; it *detects and "
        "reports* the rest, so an existing install is upgraded rather than silently "
        "shadowed. Compatibility locations stay valid inputs and are never written: "
        "migrating is re-run `install-host`, then delete the file it names. `~` is "
        "`%USERPROFILE%` on Windows and the XDG roots honour `$XDG_CONFIG_HOME`; "
        "the tokens below are what the data stores.",
        "",
        "| Host | Global (preferred) | Project (preferred) | "
        "Compatibility (detected, never written) |",
        "|---|---|---|---|",
    ]
    for host_id in sorted(hosts):
        host = hosts[host_id]
        paths = host["install_paths"]
        if not host["installable"]:
            lines.append(
                f"| `{host_id}` | *n/a* — the plugin's own "
                f"`{host['shim']['installed']}` | *n/a* | "
                f"{_install_path_cell(paths['project'] + paths['global'])} "
                "(non-plugin install) |"
            )
            continue
        lines.append(
            f"| `{host_id}` | {_install_path_cell(paths['global'])} | "
            f"{_install_path_cell(paths['project'])} | "
            f"{_install_path_cell(paths['legacy'])} |"
        )
    lines += [
        "",
        "## After a plugin update",
        "",
        "A plugin update **changes the skill directory path** — the Claude plugin "
        "cache is keyed by commit hash — so every installed shim's baked prefix "
        "goes stale. That is the common case, not an edge case, and it is one "
        "command:",
        "",
        "```bash",
        'uv run --project "$SKILL" -- python "$SKILL/multi_llm.py" install-host '
        "--check --all   # what moved",
        'uv run --project "$SKILL" -- python "$SKILL/multi_llm.py" install-host '
        "--all           # re-render every installed shim",
        "```",
        "",
        "Repair is always re-render, never in-place patching, and a re-install with "
        "nothing changed is byte-identical and does nothing. A shim you edited by "
        "hand is **never** overwritten silently: the install stops and names the "
        "file, and `--force` keeps your version as `<shim>.local.bak`. The inverse "
        "is `uninstall-host <host> [--global|--project|--all] [--dry-run]`, which "
        "removes only files carrying our `multi_llm_shim` block — identified by "
        "that block, never by filename.",
    ]
    return "\n".join(lines) + "\n"


def _bootstrap_hint() -> str:
    """How to create the page, since this script never creates it itself.

    The renderer owns the block *between* the markers and nothing else: the
    comment header above ``HOST_DOC_BEGIN`` and the footer link row below
    ``HOST_DOC_END`` are hand-written and have no source to be rendered from.
    So both failure messages below end in the same instruction rather than in a
    silent skip or a conjured file.
    """
    return (
        f"Create {HOST_DOC} carrying both markers —\n"
        f"  {HOST_DOC_BEGIN}\n  {HOST_DOC_END}\n"
        "— with the hand-written header above the first and the footer link "
        "row below the second, then re-run `python "
        "hosts/render_capabilities.py` to fill the block."
    )


def _missing_markers_message() -> str:
    return (
        f"ERROR: {HOST_DOC} carries no generated-host-install markers. Add\n"
        f"  {HOST_DOC_BEGIN}\n  {HOST_DOC_END}\n"
        "where the section belongs, then re-run this script."
    )


def host_doc_problem(host_doc: Optional[Path] = None) -> Optional[str]:
    """Why the host doc cannot be rendered into, or ``None`` when it can.

    Absence and a marker-less file are **one** class of failure — there is no
    block for this script to own — and both are reported, never repaired.
    Skipping either was safe only while the target was the always-present
    ``README.md``; against ``docs/hosts.md`` a skip lets ``--check`` print
    "up to date" for a tree carrying no host-install page at all, which is the
    one thing that guard exists to catch.
    """
    host_doc = host_doc_path() if host_doc is None else host_doc
    if not host_doc.is_file():
        return (
            f"ERROR: {HOST_DOC} does not exist ({host_doc}). This script fills "
            "in the block between two markers; it never creates the page. "
            + _bootstrap_hint()
        )
    body = host_doc.read_text(encoding="utf-8")
    if HOST_DOC_BEGIN not in body or HOST_DOC_END not in body:
        return _missing_markers_message()
    return None


def host_doc_with_section(current: str, base: Optional[str] = None) -> str:
    """*current* host doc with the generated block replaced (markers preserved)."""
    section = render_host_doc_section(base)
    block = f"{HOST_DOC_BEGIN}\n\n{section}\n{HOST_DOC_END}"
    start = current.find(HOST_DOC_BEGIN)
    end = current.find(HOST_DOC_END)
    if start < 0 or end < 0:
        # Reachable only for a caller that reads the file itself; `main()` asks
        # `host_doc_problem()` first, so a CLI run reports this as a failure
        # rather than unwinding a SystemExit through it.
        raise SystemExit(_missing_markers_message())
    return current[:start] + block + current[end + len(HOST_DOC_END):]


def main(argv: Optional[Sequence[str]] = None) -> int:
    bootstrap_streams()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true",
        help="Exit 1 if either generated copy differs from a fresh render "
             "(the CI staleness guard).",
    )
    parser.add_argument(
        "--stdout", action="store_true", help="Print the render; write nothing."
    )
    parser.add_argument(
        "--host-doc", "--readme", dest="host_doc", action="store_true",
        help=f"Operate on {HOST_DOC}'s generated host-install section instead of "
             "references/host-capabilities.md. (`--readme` is the former spelling, "
             "kept working for anything that still types it.)",
    )
    args = parser.parse_args(list(argv) if argv is not None else None)

    if args.stdout:
        sys.stdout.write(
            render_host_doc_section() if args.host_doc else render()
        )
        return 0

    text = render()
    target = SKILL_ROOT / OUTPUT
    host_doc = host_doc_path()
    if args.check:
        failures = []
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != text:
            failures.append(OUTPUT)
        # A missing or marker-less host doc is a failure, not a skipped step:
        # "the install page for two of the three hosts does not exist" must
        # never render as "up to date". Reported with its own message, because
        # "re-run the renderer and commit" is not the fix for either.
        problem = host_doc_problem(host_doc)
        if problem is None:
            body = host_doc.read_text(encoding="utf-8")
            if host_doc_with_section(body) != body:
                failures.append(HOST_DOC)
        if not failures and problem is None:
            print(f"{OUTPUT} and {HOST_DOC} are up to date.")
            return 0
        if failures:
            print(
                f"ERROR: {', '.join(failures)} stale. Generated from "
                "hosts/capabilities.yaml — re-run `python "
                "hosts/render_capabilities.py` and commit the result.",
                file=sys.stderr,
            )
        if problem is not None:
            print(problem, file=sys.stderr)
        return 1
    if not args.host_doc:
        target.write_text(text, encoding="utf-8")
        print(f"wrote {OUTPUT}")
    # The write path **refuses** rather than creating the page or skipping it.
    # This script keys on the markers, not on the filename (see HOST_DOC), so a
    # write into a file that has neither would have nowhere to land — and a
    # write into a file that does not exist would have to invent the
    # hand-written header and footer around them. Both end at the same
    # bootstrap instruction, and both are exit 1: a first render that silently
    # did nothing is exactly the failure `--check` above is being taught to
    # catch, and it must not be reachable from the write path either.
    problem = host_doc_problem(host_doc)
    if problem is not None:
        print(problem, file=sys.stderr)
        return 1
    body = host_doc.read_text(encoding="utf-8")
    host_doc.write_text(host_doc_with_section(body), encoding="utf-8")
    print(f"wrote {HOST_DOC} (generated host-install section)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
